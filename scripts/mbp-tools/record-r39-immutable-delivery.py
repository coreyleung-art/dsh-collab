#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""record-r39-immutable-delivery.py —— 归档 R39：交付物「内容寻址 + 幂等」，消灭卡/板漂移

背景（2026-10-03 对端抓到**两处**卡/板漂移，根因都是我）：
  我在卡还在途中时**反复原地重发同一个板键**（v3→v4→v5→v6→v7）
  ⇒ 卡上写的 sha256/文件数必然追不上板 ⇒ 对端按卡核对会看到「卡文与板值不一致」。
  对端提议「PUT 后冻结、按 version 取」——**约定正确，但约定会被忘**。
  ⇒ 本规则给出**结构解**，使漂移在结构上不可能。
"""
import io
import os

H = os.path.expanduser("~/dsh-collab/hazards")

p = os.path.join(H, "rules.md")
s = io.open(p, encoding="utf-8").read()
s = s.replace("R1–R38 + R025", "R1–R39 + R025", 1)
s = s.replace(
    "## R27–R38（2026-10-03 建立 · 工具契约 + 判据有效性 + 跨端投递 + 结构式删除 + 约定守卫 + 判据强度 + 脚本载体 + 退出码语义 + 交付/复现）",
    "## R27–R39（2026-10-03 建立 · 判据/工具/交付 三族规则）", 1)

row = ("| R39 | **交付物用「内容寻址 + 幂等」消灭卡/板漂移**：① 板键带**内容哈希后缀**"
       "（`<name>-<sha8>.tgz-b64`）⇒ 换内容必换键，**旧卡永远有效**；"
       "② 发布前先 GET，**同哈希则跳过 PUT**（幂等，不抬 version、不制造困惑）；"
       "③ 卡上给**完整 64 位哈希**。⇒ **不要靠「PUT 后冻结」这种约定**——约定会被忘，结构不会 |\n")
s = s.replace('| R31 | **判据"什么都没测到"必须报失败，不得报成功**',
              row + '| R31 | **判据"什么都没测到"必须报失败，不得报成功**', 1)

inst = '''
> **R39 实例**（2026-10-03 · 对端**两次**抓到我的卡/板漂移）：
> · 我卡上写 `sha256=5101b86b…`，对端取板实测 `31cf8203…` ⇒ 漂移；
> · 我卡上写 `v6 / 13 文件`，对端取板实测 `v7 / 14 文件`（我发卡后又加了 `verify-remote-package.py` 并重发）⇒ 再漂移。
> **根因**：我在**卡还在途中**时反复**原地重发同一个板键**。对端提议「PUT 后冻结、按 version 取」——
> 对，但**约定靠记性**。⇒ 我改成**结构**：键带内容哈希后缀 + 同哈希跳过 PUT。
> 实测：同内容再发 ⇒ **同键、同哈希、PUT 被跳过**（`跳过（已存在同哈希内容）`）
> ⇒ **换内容必换键 ⇒ 卡指向的键永不改变 ⇒ 漂移在结构上不可能**。
> ★ 与 R34 一脉相承：**能在结构上消灭的，不要留给约定。**
'''
s = s.replace("\n## R025（本目录的规则来源", inst + "\n## R025（本目录的规则来源", 1)
io.open(p, "w", encoding="utf-8").write(s)
print("✅ rules.md: R39 入册，条目 %d" % len([l for l in s.splitlines() if l.startswith("| R")]))

p2 = os.path.join(H, "INDEX.md")
t = io.open(p2, encoding="utf-8").read()
t = t.replace("R1–R38 + R025", "R1–R39 + R025", 1)
a = "| **G8b** | **SSE 断连频率**"
add = ("| **G17** | ★ **卡/板漂移（对端两次抓到，根因都是我）**：我在卡在途时**原地重发同一板键**"
       "（v3→…→v7）⇒ 卡上的 sha256/文件数与板上不一致。**对端提议「PUT 后冻结」正确但靠记性**；"
       "我改为**结构解**：`publish-package.py` 用**内容寻址键**（`-<sha8>`）+ **同哈希跳过 PUT**（幂等）"
       "⇒ 换内容必换键，漂移结构上不可能（实测同内容重发被跳过）。→ 立 **R39** | ✅ 已修（结构级） |\n")
assert a in t
io.open(p2, "w", encoding="utf-8").write(t.replace(a, add + a, 1))
