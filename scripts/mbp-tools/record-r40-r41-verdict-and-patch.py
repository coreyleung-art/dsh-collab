"""record-r40-r41-verdict-and-patch.py —— 归档「判定单一真相源」与「补丁盲命中」两条规则

来源：2026-10-03 **重启前审查**中发现（并当场修好、用真实阻断样本回归）：
  ① 同一条审查脚本的 `--json` 分支与人读分支**判定相反**
     （json 把 stub-limited 当阻断 ⇒ exit 1；人读分支按"有自查证据"降级 ⇒ exit 0）
     而插件工具只看退出码 ⇒ **工具报"未通过"、手跑脚本报"可以重启"**。
  ② 我修它时，`str.replace(..., 1)` **盲命中**，打到了新插入的函数体里
     ⇒ 先造成**自我递归**（RecursionError），又误删人读分支的内联阻断逻辑
     ⇒ 那一版**人读分支只剩 boot-sandbox 一项阻断 = 重启门自身假绿**。
     ★ 关键在于：`py_compile` 语法通过、`--json` 还能报错，**只有"用手跑 + 用已知阻断样本回归"才暴露**。
"""
