s = s.replace("## R27–R39（2026-10-03 建立 · 判据/工具/交付 三族规则）",
              "## R27–R41（2026-10-03 建立 · 判据 / 工具 / 交付 / 判定同源）", 1)

rows = ("| R40 | **一条判据的多个出口必须同源** —— 人读输出、`--json`、被工具调用的退出码，"
        "**只能由同一处判定逻辑产出**。多出口各算一遍必然分叉（实测：同一次审查，"
        "工具报「未通过」而手跑报「可以重启」）。**判定抽成单一函数，出口只做渲染** |\n"
        "| R41 | **打补丁必须验证命中位置，并用已知样本回归** —— `replace(..., 1)` 会**盲命中第一处**，"
        "可能打到新插入的代码里（实测：把新函数改成自我递归，又误删了另一分支的阻断逻辑 ⇒ **门自身假绿**）。"
        "⇒ 改动后**必须**：① 打印/确认命中处 ② 两分支对跑 ③ **注入一个已知阻断样本**验证仍会拦 |\n")
s = s.replace('| R31 | **判据"什么都没测到"必须报失败，不得报成功**',
              rows + '| R31 | **判据"什么都没测到"必须报失败，不得报成功**', 1)

inst = '''
> **R40/R41 实例**（2026-10-03 · **重启前审查**中查出，属"门自己的门"）：
> `restart-audit.py` 有两个人读/机器出口，判定逻辑各写一遍：
> · 人读分支：`stub-limited` **有自查证据** ⇒ 降级 ⚠️、不阻断 ⇒ **exit 0（可以重启）**
> · `--json` 分支：`smoke == "stub-limited"` ⇒ **一律当阻断** ⇒ **exit 1**
> 而插件工具 `const ok = r.code === 0` ⇒ **工具判 blocked、手跑判 pass**（同一份数据两个结论）。
> **修的时候我又踩了第二个坑**：用 `replace(..., 1)` 打补丁，**盲命中**了刚插入的函数体
> ⇒ 先 RecursionError，再误删人读分支的内联阻断 ⇒ **那一版人读分支只剩 boot-sandbox 一项阻断
> = 重启门自身假绿**（真正跳过所有插件阻断）。
> ★ 只有「手跑 + **注入已知阻断样本**」才暴露它 —— `py_compile` 通过、`--json` 也能报错，
>   静态检查一律看不见。**修完用正负样本回归，不是可选项。**
> 修后实测：注入一个语法错的假插件 ⇒ 人读 exit 1 / `--json` exit 1 且 `_blockers` 列出该插件；
> 清理后两者都 exit 0。✅
'''
