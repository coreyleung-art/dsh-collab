#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
对外正式版清理：把文档里"对内讲的话/修订痕迹"全部去掉，只保留正式标准表述。
- 删除：版本替代说明、旧版作废对照、修正记录、内部版本号、"本版/旧版/重写/作废"等
- 替换：把"为什么作废"改成"为什么这样安排"等直接陈述
用法: python3 clean-external.py <in.md> <out.md>

★ 约束门（⑩）：N/A —— 本工具【不执行外部命令、不删除数据、不修改权限】。
依据：r006-debt-assess.py 机械扫描未检出以下原语：
      subprocess / os.system / eval / exec / os.remove / rmtree /
      os.chmod / os.chown / os.kill / pkill / launchctl unload / 任意写路径参数
★ 限度：此为【模式匹配】结果，可能有漏；引入上述任一原语时须更新本声明。
"""
__version__ = '1.0.0'  # ★ R006 ⑥ 唯一版本声明处（补课生成）

import re, sys, os


# ★ R006 ⑦ 统一日志：固定路径，失败也留痕（r006-retrofit-apply 自足插入）
LOG = os.path.expanduser("~/dsh-collab/logs/clean-external.log")


def log(msg):
    """★ R006 ⑦：固定路径日志；失败也留痕。"""
    import time as _t
    try:
        os.makedirs(os.path.dirname(LOG), exist_ok=True)
        with open(LOG, "a", encoding="utf-8") as f:
            f.write("%s %s\n" % (_t.strftime("%Y-%m-%dT%H:%M:%S"), msg))
    except Exception:
        pass

def clean(text):
    lines = text.split("\n")
    out = []
    skip_until_hr = False
    i = 0
    while i < len(lines):
        ln = lines[i]
        s = ln.strip()

        # ---- 1) 头部版本/替代说明：删掉，改写成中性版本行 ----
        if s.startswith("> **本文件替代**") or s.startswith("> **本文件合并参考**"):
            i += 1; continue

        # ---- 2) 整节「本版的核心修正」：删到下一个 `---` ----
        if re.match(r"^##\s*★?\s*本版的核心修正", s):
            i += 1
            while i < len(lines) and not re.match(r"^---\s*$", lines[i]):
                i += 1
            if i < len(lines): i += 1
            continue

        # ---- 3) 附录里「相对 v1 的修正记录」整节：删到下一个 `## ` ----
        if re.match(r"^##\s*B\.2", s) or re.match(r"^##\s*★?\s*本版相对", s):
            i += 1
            while i < len(lines) and not re.match(r"^##\s", lines[i]):
                i += 1
            continue

        out.append(ln)
        i += 1

    text = "\n".join(out)

    # ---- 4) 逐句清理/改写 ----
    reps = [
        # 标题
        (r"# 花联网商业计划书 · 主文档 v2（修正版）", "# 花联网商业计划书"),
        (r"# 花联网商业计划书 · 主文档 v2", "# 花联网商业计划书"),
        (r"## 一、★ 公司结构（修正版）——本版最重要的一节", "## 一、公司结构 —— 最重要的一节"),
        (r"## 三、★ 公司结构（修正版）——本版最重要的一节", "## 三、公司结构 —— 最重要的一节"),
        (r"### 1\.3 为什么这个结构比旧版更清晰", "### 1.3 为什么这个结构更清晰"),
        (r"#### 红线二：对赌与治理红线（★ 本版按修正结构重写）", "#### 红线二：对赌与治理红线"),
        # 整段删除（含引导句）
        (r"\*\*本文件替代\*\*：[^\n]*\n", ""),
        (r"\*\*本文件合并参考\*\*：[^\n]*\n", ""),
        (r"上一版（v1）把公司结构写错了[^\n]*\n", ""),
        (r"\*\*这句话一句话记住本版的结构\*\*：\n", ""),
        (r"\*\*一句话记住本版的结构\*\*：\n", ""),
        (r"> \*\*这一节是本版与上一版差别最大的地方。\*\*[^\n]*\n", ""),
        (r"\*\*「1000 万元」这件事，旧版的说法是[^\n]*\n", ""),
        (r"\*\*为什么作废\*\*：", "**为什么这样安排**："),
        (r"\*\*这个说法整体作废。\*\*", ""),
        (r"这是本版改动最大的地方之一，所以单独用一节写清楚。\n", ""),
        (r"\*\*这一节是旧版错得最严重的地方，必须重新说清楚。\*\*\n", ""),
        (r"\*\*旧版错在哪\*\*：[^\n]*\n", ""),
        (r"\*\*⚠️ 旧版作废原话\*\*：[^\n]*\n", ""),
        (r"\*\*⚠️ 旧版作废的结构\*\*：[^\n]*\n", ""),
        # 句子级替换
        (r"本版按修正后的结构整体重写。", ""),
        (r"本版把这四处全部作废，并按修正后的结构重写。", ""),
        (r"本版全部修正都集中在那里", "结构说明集中在那里"),
        (r"本节按修正后的结构重写，以下内容为唯一正确口径。", "以下内容为正式口径。"),
        (r"这等于把「股东出资」当成了「向外部投资人融资」，并因此凭空造出一个估值和一个出让比例。", ""),
        (r"\*\*此前把两者混成「80 万元」是不严谨的，本版拆开并分别标注性质。\*\*", ""),
        (r"\*\*⚠️ 一类历史上写错、本版已修正的地方\*\*：旧版把城内运营团队写成「主管 1 + 运营 2 + 客服 2 = 5 人」。\*\*本版按修正后的边界改为", "**⚠️ 城内运营团队口径**："),
        (r"内部文件里曾出现过 58 万元、75 万元两个版本，\*\*均已作废\*\*。", ""),
        (r"\*\*旧版的做法\*\*是在公司层面引入[^\n]*\n", ""),
        (r"\*\*这套结构现在已经作废\*\*，原因很直接：", "**为什么这样设计**："),
        (r"\*\*在公司结构修正之后（资方在创始人个人层面、声通在橙果内部），这套结构不再适用，相关推演结论作废。\*\* 修正后的控制权方案是：", "**控制权方案**："),
        (r"\*\*旧版的「双层有限合伙」结构已作废。\*\*", ""),
        (r"6\. \*\*它会因为前提变化而修订\*\*[^\n]*\n", ""),
        # 表头去修订列
        (r"\| # \| ❌ 旧版作废的写法（不得再出现在任何对外文件中） \| ✅ 修正后的正确写法 \|", "| # | 常见误解 | 正式口径 |"),
        (r"\| 修正前（作废） \| 修正后（本版采用） \|", "| 以往做法 | 现行方案 |"),
        (r"\| v1 的错误写法（已作废） \| v2 的正确口径 \|", "| 常见误解 | 正式口径 |"),
        (r"\| ~~双层有限合伙~~（\*\*前提已不成立，作废\*\*） \|", "| ~~双层有限合伙~~（**不适用**） |"),
    ]
    for a, b in reps:
        text = re.sub(a, b, text)

    # ---- 5) 全文残余词替换（保守）----
    text = text.replace("（修正版）", "")
    text = text.replace("修正版", "正式版")
    text = re.sub(r"v2\.0", "", text)
    text = re.sub(r"v1\.2|v1\.1|v1", "", text)
    # 清掉连续空行
    text = re.sub(r"\n{4,}", "\n\n\n", text)
    return text

def main():
    if len(sys.argv) < 3:
        print("用法: clean-external.py <in.md> <out.md>"); sys.exit(1)
    src, dst = sys.argv[1], sys.argv[2]
    raw = open(src, encoding="utf-8").read()
    out = clean(raw)
    open(dst, "w", encoding="utf-8").write(out)
    # 统计残余
    resid = {k: len(re.findall(k, out)) for k in ["旧版","本版","作废","重写","v1","修正记录"]}
    resid = {k: v for k, v in resid.items() if v}
    print(f"✅ {os.path.basename(dst)}  ({len(out)} 字符)")
    print(f"   残余修订词: {resid if resid else '无 ✓'}")

if __name__ == "__main__":
    main()
